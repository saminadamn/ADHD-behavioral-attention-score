"""
Run the questionnaire-derived classroom turns (tests/fixtures/questionnaire_cases.py)
through the full LangGraph pipeline as one continuous multi-turn session --
carrying BAS and attention-state memory across turns the way a real session
would -- and write the result table to docs/questionnaire_validation.md.

This is a validation *demonstration*, not a validation *study*: the pipeline
classifies one classroom turn (teacher prompt + student response + response
latency) at a time, not a 50-item self-report questionnaire. Each case was
written to embody one clinical construct from a standard assessment
(DSM-5-TR / ASRS-style inattention and hyperactivity-impulsivity items,
Barkley BDEFS executive-function/emotional-regulation items), to check
whether the pipeline's five behavioral signals move the way that construct
implies. See docs/questionnaire_validation.md for the full write-up and its
limitations.

Run:
    cd backend
    python scripts/validate_against_assessment_questionnaire.py
"""
from __future__ import annotations
import os
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.pipeline import run_turn  # noqa: E402
from tests.fixtures.questionnaire_cases import CASES  # noqa: E402

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_PATH = os.path.join(REPO_ROOT, "docs", "questionnaire_validation.md")


def run_session() -> list[dict]:
    bas = 50.0
    history: list[float] = []
    prev_state = None
    rows = []

    for item, construct, prompt, response, latency, expected in CASES:
        result = run_turn(
            teacher_prompt=prompt,
            student_response=response,
            response_latency=latency,
            previous_attention_state=prev_state,
            current_bas=bas,
            bas_history=history,
        )
        state = result.get("attention_state")
        bas = result.get("current_bas", bas)
        history = result.get("bas_history", history)
        prev_state = state
        rows.append({
            "item": item,
            "construct": construct,
            "prompt": prompt,
            "response": response,
            "latency": latency,
            "expected": expected,
            "state": state,
            "confidence": result.get("confidence", 0.0),
            "reward": result.get("reward", 0.0),
            "bas": bas,
            "tier": result.get("tier", ""),
            "intervention": result.get("intervention", ""),
            "match": state == expected,
        })
    return rows


def render_markdown(rows: list[dict]) -> str:
    n_match = sum(r["match"] for r in rows)
    lines = [
        "# Questionnaire-derived validation results",
        "",
        f"_Generated by `backend/scripts/validate_against_assessment_questionnaire.py` "
        f"on {datetime.now(timezone.utc).strftime('%Y-%m-%d')}._",
        "",
        "## What this is",
        "",
        "Ten classroom turns, each written to embody one construct from a standard "
        "50-item clinical ADHD assessment (DSM-5-TR / ASRS-style inattention and "
        "hyperactivity-impulsivity items, Barkley BDEFS executive-function items), "
        "run through the full pipeline "
        "(`signal_extractor -> state_classifier -> reward_modeler -> bas_tracker -> "
        "intervention_generator`) as one continuous session, with BAS and attention-"
        "state memory carried across turns the way a real session would be.",
        "",
        "## What this is not",
        "",
        "**Not a validation study against the questionnaire.** The pipeline classifies "
        "one classroom turn (a teacher prompt, a student response, and the response "
        "latency) into Focused / Distracted / Impulsive -- it does not take a 50-item "
        "self-report, and a single turn cannot establish onset, cross-setting presence, "
        "or impairment, which is what an actual clinical assessment measures. These "
        "turns were constructed by hand to *embody* one construct each, specifically so "
        "any gap between what the construct implies and what the pipeline's five "
        "behavioral signals can see from text alone would show up as a mismatch -- see "
        "`docs/model_limitations.md` for three such gaps that were found and fixed this "
        "way.",
        "",
        f"## Result: {n_match}/{len(rows)} match the expected label",
        "",
        "| Item | Construct | Result | Conf | Reward | BAS | Tier |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        mark = "✅" if r["match"] else "⚠️"
        lines.append(
            f"| {r['item']} | {r['construct']} | {mark} **{r['state']}** "
            f"(expected {r['expected']}) | {r['confidence']:.0%} | "
            f"{r['reward']:+.2f} | {r['bas']:.1f} | {r['tier']} |"
        )

    lines += [
        "",
        f"**Final BAS: {rows[-1]['bas']:.1f}**  "
        f"|  **Trajectory:** {[round(r['bas'], 1) for r in rows]}",
        "",
        "## Turn-by-turn detail",
        "",
    ]
    for r in rows:
        lines += [
            f"### {r['item']} — {r['construct']}",
            "",
            f"- **Teacher prompt:** {r['prompt']}",
            f"- **Student response:** {r['response']!r}  (latency: {r['latency']}s)",
            f"- **Classified:** {r['state']} ({r['confidence']:.0%} confidence) "
            f"— reward {r['reward']:+.2f}, BAS now {r['bas']:.1f}",
            f"- **Recommended intervention ({r['tier']}):** {r['intervention']}",
            "",
        ]

    lines += [
        "## Reproduce this",
        "",
        "```bash",
        "cd backend",
        "python scripts/validate_against_assessment_questionnaire.py",
        "```",
        "",
        "The same ten cases are also asserted as regression tests in "
        "`backend/tests/test_questionnaire_constructs.py` "
        "(`python -m pytest tests/test_questionnaire_constructs.py -v`), so a future "
        "change to the pipeline that breaks one of these constructs fails CI rather "
        "than silently drifting.",
        "",
    ]
    return "\n".join(lines)


def main():
    rows = run_session()
    markdown = render_markdown(rows)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write(markdown)
    n_match = sum(r["match"] for r in rows)
    print(f"{n_match}/{len(rows)} cases matched their expected label.")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
